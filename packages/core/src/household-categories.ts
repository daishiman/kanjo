/**
 * 家計(個人)の標準大項目/中項目。
 *
 * MF 明細を取り込む前や、まだその費目で払ったことがない支出でも記帳できるようにするための土台。
 * 名前は MF の大項目に寄せてある。同名なら buildCandidates 側で実データの大項目に吸収され、
 * 「同じ費目が標準と実績で二重に並ぶ」ことが起きない。
 *
 * 収録の方針:
 * - 生活に必ず出るもの(食費・日用品・水道光熱・通信・住まい)を最優先で置く
 * - 家の購入まわり(頭金・仲介手数料・登記費用・不動産取得税・固定資産税・引越し)は
 *   一生で数回しか出ないぶん、その場で科目を考えるのが一番つらい。中項目まで用意しておく
 * - 税と社会保険、各種保険は「毎年決まって出るのに費目名が思い出せない」代表格なので独立させる
 */

export type HouseholdGroup =
  | '住まい'
  | '毎日の暮らし'
  | '移動・車'
  | '税・保険'
  | 'こども・学び'
  | 'たのしみ・その他';

