/**
 * 図・表の「見方」の正本。
 *
 * 用語辞書(glossary.ts)は語の意味を説明するもので、こちらは図そのものの読み方を説明する。
 * 粒度が違うので混ぜない(辞書側は「画面で <Term> として使われていること」を検査するため、
 * 図の説明を混ぜると検査が通らない)。
 *
 * 3行の意味は全図で同じ順に固定する:
 *   shows … 何を表しているか
 *   read  … どこを見ればいいか
 *   act   … 読んだ結果、次に何をするか
 * 順番が毎回同じなら、2枚目以降の図は説明を読まずに数字へ入れる。
 *
 * 1行は全角40〜50字まで。超えるなら2つの図に分けるか、文を削る。
 */
export interface FigureGuide {
  /** 何を表しているか */
  shows: string;
  /** どこを見ればいいか */
  read: string;
  /** 読んだ結果、次に何をするか */
  act: string;
}

